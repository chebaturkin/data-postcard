export const LOCALE_KEY = 'data-postcard:language';
const supported = value => value === 'ru' || value === 'en';
export function resolveLocale({ search = '', stored, languages = [] } = {}) {
  let direct;
  try { direct = new URLSearchParams(search).get('lang'); } catch {}
  if (supported(direct)) return direct;
  if (supported(stored)) return stored;
  for (const language of languages || []) {
    const base = String(language).toLowerCase().split('-')[0];
    if (supported(base)) return base;
  }
  return 'en';
}
function initialLocale() {
  let stored;
  try { stored = globalThis.localStorage?.getItem(LOCALE_KEY); } catch {}
  return resolveLocale({search:globalThis.location?.search,stored,languages:globalThis.navigator?.languages || [globalThis.navigator?.language].filter(Boolean)});
}
let locale = initialLocale();
const subscribers = new Set();
export const getLocale = () => locale;
export const localeTag = () => locale === 'ru' ? 'ru-RU' : 'en-US';
export function t(key, values = {}) {
  if (locale === 'en' && Number(values.count) === 1 && dictionaries.en[key + 'One']) key += 'One';
  const message = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
  return message.replace(/\{(\w+)\}/g, (token, name) => Object.hasOwn(values, name) ? String(values[name] ?? '') : token);
}
export function setLocale(next, options = {}) {
  if (!supported(next)) return;
  const previous = locale;
  locale = next;
  try { (options.storage || globalThis.localStorage)?.setItem(LOCALE_KEY, locale); } catch {}
  try {
    const url = new URL(options.url || globalThis.location?.href);
    url.searchParams.set('lang', locale);
    const history = options.history || globalThis.history;
    history?.replaceState(history.state, '', url.href);
  } catch {}
  if (previous !== locale) {
    if (globalThis.document) applyStatic();
    subscribers.forEach(callback => callback(previous));
  }
}
// Only messages produced by this app are re-rendered; user data never enters this function.
export function translateMessage(message, from) {
  const source = dictionaries[from || (locale === 'ru' ? 'en' : 'ru')];
  for (const [key, pattern] of Object.entries(source).sort((a,b) => b[1].replace(/\{\w+\}/g,'').length - a[1].replace(/\{\w+\}/g,'').length)) {
    const names = [];
    const parts = pattern.split(/\{(\w+)\}/g);
    const expression = parts.map((part,index) => index % 2 ? (names.push(part), '(.*?)') : part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('');
    const match = String(message ?? '').match(new RegExp('^'+expression+'$', 's'));
    if (match) return t(key, Object.fromEntries(names.map((name,index)=>[name,match[index+1]])));
  }
  return message;
}
export function applyStatic() {
  document.documentElement.lang = locale;
  document.querySelectorAll('[data-i18n]').forEach(node => { node.textContent = t(node.dataset.i18n); });
  for (const attribute of ['aria-label','title','placeholder','content','alt']) {
    document.querySelectorAll('[data-i18n-'+attribute+']').forEach(node => node.setAttribute(attribute,t(node.getAttribute('data-i18n-'+attribute))));
  }
  document.querySelectorAll('[data-language]').forEach(button=>button.setAttribute('aria-pressed',String(button.dataset.language === locale)));
  document.querySelector('[data-language-control]')?.setAttribute('aria-label',t('language'));
}
export function mountLocale(callback) {
  applyStatic();
  if (callback) subscribers.add(callback);
  document.querySelectorAll('[data-language]').forEach(button=>button.addEventListener('click',()=>setLocale(button.dataset.language)));
}
